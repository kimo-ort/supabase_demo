CREATE TABLE IF NOT EXISTS contactos (
    id_contacto BIGINT generated by default as identity not null PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    email VARCHAR(100) NOT NULL,
    telefono VARCHAR(13) NOT NULL
);


